// Writes api/_vigil-config.js from the assistant's knowledge, so the live
// voice server function carries exactly the same approved facts as the chat.
// Runs before every build: npm run vigil:config
import { writeFileSync } from "node:fs";
import { systemPrompt, TOOLS } from "../src/scripts/assistant/prompt";

const out = `// Generated by scripts/vigil-config.ts from src/scripts/assistant. Do not edit by hand.\nexport const SYSTEM_PROMPT = ${JSON.stringify(systemPrompt())};\nexport const TOOLS = ${JSON.stringify(TOOLS)};\n`;
writeFileSync(`${process.cwd()}/api/_vigil-config.js`, out);
console.log("api/_vigil-config.js written");
